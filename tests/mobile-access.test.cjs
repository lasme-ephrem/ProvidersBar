const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { createMobileAccess } = require('../lib/mobile-access.cjs');
test('Mobile access persists, rotates the pairing code, revokes old cookies and stops listening', async t => {
  const dataDir=await fs.mkdtemp(path.join(os.tmpdir(),'providersbar-mobile-test-'));
  const safeStorage={isEncryptionAvailable:()=>true,encryptString:s=>Buffer.from(s.split('').reverse().join('')),decryptString:b=>b.toString().split('').reverse().join('')};
  const options={root:path.resolve(__dirname,'..'),dataDir,safeStorage,port:0,getState:()=>({providers:[]}),sync:async()=>{}};
  let access=createMobileAccess(options);
  t.after(async()=>{await access.close();await fs.rm(dataDir,{recursive:true,force:true});});
  await access.load();assert.equal(access.info().enabled,false);
  const first=await access.update({enabled:true,origin:'',rotate:false});
  assert.equal((await fetch(first.localUrl+'/api/state',{headers:{Cookie:'pb_mobile='+first.code}})).status,200);
  await access.close();access=createMobileAccess(options);await access.load();assert.equal(access.info().code,first.code);assert.equal(access.info().enabled,true);
  const rotated=await access.update({enabled:true,origin:'',rotate:true});assert.notEqual(rotated.code,first.code);
  assert.equal((await fetch(rotated.localUrl+'/api/state',{headers:{Cookie:'pb_mobile='+first.code}})).status,401);
  assert.equal((await fetch(rotated.localUrl+'/api/state',{headers:{Cookie:'pb_mobile='+rotated.code}})).status,200);
  assert.ok(!(await fs.readFile(path.join(dataDir,'mobile-access.json'),'utf8')).includes(rotated.code));
  await assert.rejects(access.update({enabled:true,origin:'https://evil.test',rotate:false}));assert.equal(access.info().enabled,true);
  await access.update({enabled:false,origin:'',rotate:false});assert.equal(access.info().enabled,false);
  await assert.rejects(fetch(rotated.localUrl));
});
